// selfsim.js — the machine inside the machine.
//
// Builds a smaller copy of the N16 processor (no multiplier, no shifter),
// and turns its netlist into Turtle source: tables that programs/itself.tt
// walks to simulate that processor gate by gate. The inner processor runs
// INNER_PROGRAM, assembled here with the same assembler as everything else.

import { buildCPU } from './cpu.js';
import { optimize } from './netlist.js';
import { assemble } from './asm.js';
import { K_NAND, K_MEM, K_DFF } from './hdl.js';

export const INNER_PROGRAM = `
; runs inside the simulated processor
        li   r1, 0          ; a counter
        li   r2, 0          ; Fibonacci numbers
        li   r3, 1
loop:   add  r1, r1, 1
        add  r4, r2, r3
        mov  r2, r3
        mov  r3, r4
        st   [r1 + 64], r4  ; into the inner machine's memory
        xor  r5, r5, r1
        jmp  loop
`;

export function innerNetlist() {
  return optimize(buildCPU({ multiply: false, shift: false }));
}

/** Turtle source declaring the inner netlist and inner ROM. */
export function innerSource(nl, program = INNER_PROGRAM) {
  const N = nl.size;
  const ZERO = N, ONE = N + 1; // constants live after the last net
  const remap = (n) => (n === 0 ? ZERO : n === 1 ? ONE : n);
  nl.dffs.forEach((f, i) => { if (f.q !== 2 + i) throw new Error('flip-flops must come first'); });
  const ga = new Array(N).fill(0), gb = new Array(N).fill(0);
  const sched = [];
  let runStart = -1;
  const close = (n) => { if (runStart >= 0) { sched.push(0, runStart, n); runStart = -1; } };
  for (let n = 2; n < N; n++) {
    const k = nl.kind[n];
    if (k === K_NAND) {
      ga[n] = remap(nl.in0[n]);
      gb[n] = remap(nl.in1[n]);
      if (runStart < 0) runStart = n;
    } else {
      close(n);
      if (k === K_MEM && nl.in1[n] === 0) {
        const p = nl.readPorts[nl.in0[n]];
        p.data.forEach((d, i) => { if (d !== n + i) throw new Error('port data nets must be contiguous'); });
        sched.push(1, nl.in0[n], n);
      }
    }
  }
  close(N);
  sched.push(2, 0, 0);
  const wp = nl.writePorts[0];
  const rom = assemble(program);
  const list = (xs) => {
    const lines = [];
    for (let i = 0; i < xs.length; i += 20) lines.push('  ' + xs.slice(i, i + 20).join(', '));
    return `{\n${lines.join(',\n')}\n}`;
  };
  return `// generated by src/selfsim.js from the netlist of the inner processor
const IN_NETS = ${N};
const IN_GATES = ${nl.gateCount()};
const IN_DFFS = ${nl.dffs.length};
const IN_ZERO = ${ZERO};
const IN_ONE = ${ONE};
const IN_WE = ${remap(wp.we)};
var ga[] = ${list(ga)};
var gb[] = ${list(gb)};
var sched[] = ${list(sched)};
var port_addr[] = ${list(nl.readPorts.flatMap((p) => p.addr.map(remap)))};
var port_mem[] = { ${nl.readPorts.map((p) => (p.mem === 'ram' ? 1 : 0)).join(', ')} };
var dff_d[] = ${list(nl.dffs.map((f) => remap(f.d)))};
var wp_addr[] = { ${wp.addr.map(remap).join(', ')} };
var wp_data[] = { ${wp.data.map(remap).join(', ')} };
var inner_rom[256] = ${list([...rom.rom.subarray(0, rom.romSize)])};
`;
}
